const { GoogleGenerativeAI } = require("@google/generative-ai");
const fs = require('fs');
const path = require('path');

const genAI = new GoogleGenerativeAI(process.env.GEMINI_API_KEY);

async function run() {
  const model = genAI.getGenerativeModel({ model: "gemini-2.5-flash-lite" });
  const csvData = fs.readFileSync('news.csv', 'utf8');

  const today = new Date().toISOString().split('T')[0]; // UTC基準の当日日付

  const prompt = `
    当日の日付は${today}（UTC基準）です。
    以下のデータから記事の見出しを抽出・整理してください。英語の見出しはすべて自然な日本語に翻訳してください。機械的に要件を処理すればいい。
    ■手順
    1. 文字の羅列から「媒体・分野ごとの区切り（●●〇〇●●）」「記事の見出し」「年月日に関わる情報」のみを抽出する。これをAとする。
       以下はノイズなので無視する：ナビゲーション要素、フッター・ヘッダー、【速報】、【特報】、【】、広告、著作権表示、記事本文・要約文、市場データ表、記者名、UI要素（「category」「検索」「ログイン」「SKIP TO CONTENT」「opens new tab」「Report Ad」「advertisement」「もっと見る」等）、動画・音声・ポッドキャスト、料理レシピ、ゲーム、製品レビュー等。
    2. Aにある記事見出しを「記事の見出し」＋「媒体・分野」＋「年月日」の形で1行ごとにまとめる。
       例：「記事の見出し」(媒体名)yyyy/mm/dd
    3. 「〇日前」という曖昧な時系列情報は現在の日付から年月日を推測する。
       「1日前」「昨日」→当日の前日、「2日前」→当日の2日前、のように逆算する。
    4. 当日より3日以上前の記事見出しは削除する（当日・1日前・2日前のみ残す）。
    5. 「〇時間前」「〇分前」の記事は当日の記事として扱う。
    6. 「記事の見出し」＋「媒体・分野」＋「年月日」の形にまとめられない不明瞭な情報は削除する。
    7. 下記に示した●●で囲まれた媒体・分野ごとに記事を並べる。同一媒体内の重複は1つにまとめる。
    8. 全ての媒体・分野セクション（ロイター、ブルームバーグ、BBC、NYダイムズ、WSJ、AXIOS、日経、時事、日経・読売・産経・47・みんかぶ、「日経・読売、テクノロジー」、yahoo、AI、2ch）を必ず出力すること。途中で出力を打ち切らないこと。
    9，●●2ch●●のニュースを省略しないこと。2chカテゴリーのニュースの媒体は(2ch)とする。
    9.5 入力に見出しが1つもないセクションは、見出しを作らず「記事なし」とだけ書く。この指示文の例や架空の記事、過去の記事を出力してはならない。
    10. 各セクションの時刻設定と最大記事本数、注意事項を提示する。並び順も以下の記述に従う。以下の例にある/以降は注意、要件。
    
    ●●ロイター●●　/日本時間（UTC+9） 「ロイター、ロイタービジネス、ロイター経済、ロイター市場」の記事を統合。 40本以上の記事は提示しない。
    ●●ブルームバーグ●●　/日本時間（UTC+9） 上から順に25本の記事を提示する。25本以上の記事は提示しない。
    ●●BBC●●　/UTC 上から順に25本の記事を提示する。25本以上の記事は提示しない。記事が多いので規定量以上を表示しないように注意。日本語に翻訳する。
    ●●NYタイムズ●●　/UTC上から順に25本の記事を提示する。25本以上の記事は提示しない。記事が多いので規定量以上を表示しないように注意。日本語に翻訳する。
    ●●WSJ●●　/日本時間（UTC+9） 上から順に20本の記事を提示する。20本以上の記事は提示しない。
    ●●AXIOS●●　/UTC 上から順に20本の記事を提示する。20本以上の記事は提示しない。記事が多いので規定量以上を表示しないように注意。日本語に翻訳する。
    ●●日経●●　/日本時間（UTC+9） 上から順に10本の記事を提示する。10本以上の記事は提示しない。
    ●●時事●●　/日本時間（UTC+9） 上から順に10本の記事を提示する。10本以上の記事は提示しない。
    ●●日経・読売・産経・47・みんかぶ●●　/日本時間（UTC+9） 政治・経済・社会・ビジネス・マーケット・スポーツから偏りなく30本の記事を提示する。30本以上の記事は提示しない。
    ●●日経・読売、テクノロジー●●　/日本時間（UTC+9） 上から順に15本の記事を提示する。15本以上の記事は提示しない。
    ●●yahoo●●　/日本時間（UTC+9） ●●国内etc●●から抽出　上から順に20本の記事を提示する。20本以上の記事は提示しない。
    ●●AI●●　/日本時間（UTC+9） 上から順に10本の記事を提示する。10本以上の記事は提示しない。
    ●●2ch●●　/日本時間（UTC+9） 上から順に20本の記事を提示する。20本以上の記事は提示しない。
    
    ■補足
    - ●●日経●●と●●時事●●は入力に独立したセクションとしてある。必ずそれぞれ単独のセクションとして出力し、他のセクションとまとめない。
    - 国内etcセクションはCSV形式（カンマ区切り）で「日経1」「時事1」「yahoo1」等のラベルの後に続く文字列が見出し。
    - ヤフーセクション（●●ヤフー●●）はYahoo!ニュースのトピックス一覧。「国内」「国際」「経済」「エンタメ」「スポーツ」「IT」「科学」「地域」等のカテゴリ別に短い見出しが並ぶ。各トピック名が見出し。年月日は当日を用いる。媒体が不明の場合は「yahoo」とする。「もっと見る」「トピックス一覧」等のナビ要素は無視する。「あなたにおすすめ」以降の記事も含め、記事見出しと判断できるものは全て抽出すること。
    - AXIOSセクション（●●AXIOS●●）は米ニュースサイトAxiosの英文記事。見出しは必ず日本語に翻訳する。「〇 hours ago」「Updated」等の時間情報から日付を推測する。媒体名は「AXIOS」とする。
    - AI関連セクション（●●AI●●）はGoogleニュースのAI関連記事。「〇時間前」「〇日前」「昨日」等の時間情報から日付を推測する。「もっと見る」「検索オプション」等のナビ要素は無視する。
    - 日経・読売・産経・47・みんかぶセクション（●●日経・読売・産経・47・みんかぶ●●）は各紙のRSS見出し。行頭の[新聞名/分野]の新聞名を媒体名とする（日経、読売、産経、47、みんかぶ）。[新聞名/分野]自体は見出しに含めない。「日経・読売、テクノロジー」セクションも同様に行頭の[新聞名]を媒体名とする。
    - RSSから取得したセクション（ロイター、NYタイムズ、WSJ、AXIOS、ブルームバーグ、AI、日経・読売・産経・47・みんかぶ、「日経・読売、テクノロジー」）は、見出し末尾の（月/日 時:分）が日本時間の配信日時。年は当日の年とする。
    - 各媒体内は日付の新しい順に並べる。
    - 読者個人を教化するような自己啓発的な論説は排除。事実ベース、社会の未来像、金融市場・経済の先行きに関する報道を重視。
    - 【】この記号は使わない。この記号が混じった文章は、【】のみを削除する。

    ■最終確認
    かなりの確率で要件を守った出力ができていないはずです。もう一度、要件を守れているか確認、修正をしてください。
    とくにニュース見出し記事の不足、見出し記事・媒体・年月日の並び破綻ミスが多いです。要確認、修正。
 
    リスト：
    ${csvData}
  `;

  const result = await model.generateContent(prompt);
  const summaryText = result.response.text().replace(/[【】]/g, '');
  fs.writeFileSync('summary1.txt', summaryText);
}

run();
